#!/usr/bin/env python3
"""Generate seed.sql for the Harbour Point legacy estate.

Fixed random seed, fixed anchor date: every run produces identical data, so any
other stack can load the same file and be compared like for like.

    python seed.py > seed.sql
"""
import random
from datetime import datetime, timedelta, timezone

rng = random.Random(20261121)
ANCHOR = datetime(2026, 11, 1, 12, 0, tzinfo=timezone.utc)

FIRST = ["Amelia", "Oliver", "Isla", "George", "Ava", "Noah", "Mia", "Arthur", "Grace", "Leo",
         "Freya", "Harry", "Ivy", "Jack", "Ruby", "Charlie", "Evie", "Oscar", "Poppy", "Henry",
         "Daisy", "Alfie", "Sophie", "Freddie", "Ella"]
LAST = ["Smith", "Jones", "Taylor", "Brown", "Williams", "Wilson", "Johnson", "Davies", "Patel",
        "Robinson", "Wright", "Thompson", "Evans", "Walker", "White", "Roberts", "Green", "Hall",
        "Wood", "Jackson", "Clarke", "Hughes", "Edwards", "Turner", "Lewis"]
STREETS = ["High Street", "Station Road", "Church Lane", "Mill Road", "Victoria Road",
           "Park Avenue", "The Green", "Kings Road", "Queens Drive", "Albert Street"]
TOWNS = ["Bristol", "Leeds", "Norwich", "Exeter", "York", "Bath", "Derby", "Oxford", "Hull", "Truro"]
NARRATIVES = ["Card payment", "Direct debit", "Salary", "Standing order", "Cash withdrawal",
              "Faster payment in", "Faster payment out", "Refund", "Interest", "Transfer"]


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


out = []
w = out.append
w("-- Generated by seed.py (fixed seed). Do not edit by hand.")
w("SET search_path = core;")

# ---- customers (mainframe) -------------------------------------------------
KYC = {7: "R", 19: "R", 4: "P", 11: "P", 16: "P", 22: "P"}
NO_DOB = {9, 21}
w("INSERT INTO mainframe.customer (cust_id, cust_name, dob, email, phone, addr1, addr2, addr3, addr4, kyc_status, rel_value) VALUES")
rows = []
for i in range(1, 26):
    first, last = FIRST[i - 1], LAST[rng.randrange(len(LAST))]
    dob = "00000000" if i in NO_DOB else "%04d%02d%02d" % (rng.randint(1950, 2004), rng.randint(1, 12), rng.randint(1, 28))
    phone = "+4477009%05d" % rng.randint(0, 99999)
    addr = [f"{rng.randint(1, 120)} {rng.choice(STREETS)}", rng.choice(TOWNS), "", ""]
    if rng.random() < 0.4:
        addr[2] = "United Kingdom"
    rel = round(rng.uniform(0, 250000), 2)
    rows.append("(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)" % (
        q("CUST%06d" % i), q(f"{first} {last}"), q(dob), q(f"{first}.{last}{i}@example.test".lower()),
        q(phone), q(addr[0]), q(addr[1]), q(addr[2]), q(addr[3]), q(KYC.get(i, "V")), rel))
w(",\n".join(rows) + ";")

# ---- accounts ---------------------------------------------------------------
# 1-25 current accounts (one per customer), 26-40 savings (customers 1-15).
FROZEN, CLOSED = 5, 6
OVERDRAFT = {7: (50000, -12000), 8: (50000, -30500)}      # limit, target balance (pence)
HOLDS = {9: [(25000, 5), (10000, 2)], 10: [(75000, 10)], 11: [(5000, 1)]}   # active (days left)
EXPIRED_HOLD = 12
CAP_ACCOUNT = 40                                          # sits just under the balance ceiling

accounts, ledger, holds = [], [], []
txn = 0
for n in range(1, 41):
    acc_id = "HPB%08d" % (10000000 + n)
    cust = "CUST%06d" % (n if n <= 25 else n - 25)
    product = "CUR" if n <= 25 else "SAV"
    status = "F" if n == FROZEN else "C" if n == CLOSED else "A"
    limit = OVERDRAFT.get(n, (0, 0))[0]
    sort_code = "20-45-67" if product == "CUR" else "20-45-68"

    entries = []                                          # (when, amount, narrative)
    start = ANCHOR - timedelta(days=548)
    if n == CAP_ACCOUNT:
        entries.append((start, 9999999900, "Opening deposit"))
    else:
        bal = rng.randint(200000, 800000)
        entries.append((start, bal, "Opening deposit"))
        count = 1 if n == CLOSED else rng.randint(40, 58)
        for _ in range(count - 1 if n != CLOSED else 0):
            when = start + timedelta(minutes=rng.randint(60, 548 * 24 * 60 - 60))
            amt = rng.randint(500, 60000) * rng.choice([-1, -1, 1])
            if bal + amt < 0:
                amt = abs(amt)
            bal += amt
            entries.append((when, amt, rng.choice(NARRATIVES)))
        if n in OVERDRAFT:
            entries.append((ANCHOR - timedelta(days=1), OVERDRAFT[n][1] - bal, "Card payment"))
        if n == CLOSED:
            entries.append((ANCHOR - timedelta(days=30), -bal, "Account closure"))
    entries.sort(key=lambda e: e[0])
    balance = sum(e[1] for e in entries)
    accounts.append("(%s,%s,%s,%s,%d,%d,%s)" % (q(acc_id), q(cust), q(product), q(sort_code), balance, limit, q(status)))
    for when, amt, narr in entries:
        txn += 1
        ledger.append("(%d,%s,%s,%d,%s)" % (txn, q(acc_id), q(when.isoformat()), amt, q(narr)))
    for amt, days in HOLDS.get(n, []):
        holds.append("(%s,%d,%s)" % (q(acc_id), amt, q((ANCHOR + timedelta(days=days)).isoformat())))
    if n == EXPIRED_HOLD:
        holds.append("(%s,%d,%s)" % (q(acc_id), 40000, q((ANCHOR - timedelta(days=3)).isoformat())))

w("INSERT INTO account (account_id, cust_id, product, sort_code, ledger_bal_minor, overdraft_limit_minor, status) VALUES")
w(",\n".join(accounts) + ";")
w("INSERT INTO account_hold (account_id, amount_minor, expires_at) VALUES")
w(",\n".join(holds) + ";")
w("INSERT INTO ledger_entry (txn_id, account_id, posted_at, amount_minor, narrative) VALUES")
w(",\n".join(ledger) + ";")
w("SELECT setval('ledger_entry_txn_id_seq', %d);" % txn)

print("\n".join(out))
